# Builds src/iconPaths.js: the vector shapes (Material Design Icons, Apache-2.0) for every icon name the app uses.
# Icons are drawn with react-native-svg, so they never depend on an icon font being loaded.
import re, os, json, sys, glob
SRC=sys.argv[1]  # folder with MDI .svg files
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names=set()
for f in [os.path.join(root,'App.js')]+glob.glob(os.path.join(root,'src','**','*.js'),recursive=True):
    if f.endswith('iconPaths.js'): continue
    names|=set(re.findall(r"""['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]""",open(f,encoding='utf8').read()))
out={}
for n in sorted(names):
    p=os.path.join(SRC,n+'.svg')
    if os.path.exists(p):
        d=re.findall(r'\sd="([^"]+)"',open(p,encoding='utf8').read())
        if d: out[n]=' '.join(d)
open(os.path.join(root,'src','iconPaths.js'),'w').write('// Generated by tools/build-icons.py from Material Design Icons (pictogrammers.com, Apache-2.0). Do not edit.\nexport default '+json.dumps(out,separators=(',',':'))+';\n')
print(len(out),'icons')
